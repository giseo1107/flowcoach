package com.giseo.flowcoach.domain;

/**
 * 안내 모드. 숙련 운전자의 '잔소리' 거부감을 줄이기 위해 나눈다.
 * 한 줄 요약: 코치 = 주행 중에 말로 알려줌 / 조용 = 주행 중엔 조용히, 끝나고 리포트로.
 */
public enum CoachMode {
    /** 흐름 안내·칭찬까지 적극적으로 말한다. 초보·안심 모드. */
    COACH,
    /**
     * 주행 중에는 말하지 않는다. 위험(과속, 급제동 반복)만 짧은 경고음 + 화면 강조/팝업.
     * 습관(추월 후 미복귀, 잦은 차로 변경)은 소리 없이 화면 문장으로, 느림·칭찬은 생략. 모두 리포트에 남는다.
     */
    QUIET
}
